"""Safe local attachment handling and portable document-report bundles."""
from __future__ import annotations

import base64
import binascii
import html
import json
import os
import re
import shutil
import tempfile
import uuid
import zipfile
from pathlib import Path, PurePosixPath
from typing import Any, Iterable

MAX_ATTACHMENT_BYTES = 20 * 1024 * 1024
ALLOWED_EXTENSIONS = frozenset({".jpg", ".jpeg", ".png", ".webp", ".gif", ".bmp", ".tif", ".tiff", ".pdf"})
IMAGE_EXTENSIONS = ALLOWED_EXTENSIONS - {".pdf"}
ATTACHMENT_FOLDER = "attachments"


def safe_original_name(name: str | os.PathLike[str]) -> str:
    """Return a short display-only basename with controls and separators removed."""
    raw = str(name).replace("\\", "/").split("/")[-1]
    raw = "".join(char for char in raw if ord(char) >= 32 and ord(char) != 127).strip().strip(".")
    if not raw or raw in {".", ".."}:
        raise ValueError("اسم الملف غير صالح.")
    if len(raw) > 180:
        suffix = Path(raw).suffix[:12]
        raw = raw[: 180 - len(suffix)] + suffix
    return raw


def validate_extension(name: str | os.PathLike[str]) -> str:
    ext = Path(safe_original_name(name)).suffix.lower()
    if ext not in ALLOWED_EXTENSIONS:
        raise ValueError("يُسمح فقط بملفات الصور وPDF المدعومة.")
    return ext


def validate_attachment_content(name: str | os.PathLike[str], content: bytes) -> None:
    """Check the file signature without decoding or executing user-provided content."""
    ext = validate_extension(name)
    header = content[:1024]
    valid = {
        ".jpg": content.startswith(b"\xff\xd8\xff"),
        ".jpeg": content.startswith(b"\xff\xd8\xff"),
        ".png": content.startswith(b"\x89PNG\r\n\x1a\n"),
        ".gif": content.startswith((b"GIF87a", b"GIF89a")),
        ".bmp": content.startswith(b"BM"),
        ".webp": len(content) >= 12 and content.startswith(b"RIFF") and content[8:12] == b"WEBP",
        ".tif": content.startswith((b"II*\x00", b"MM\x00*")),
        ".tiff": content.startswith((b"II*\x00", b"MM\x00*")),
        ".pdf": b"%PDF-" in header,
    }[ext]
    if not valid:
        raise ValueError("محتوى الملف لا يطابق امتداد الصورة أو PDF المحدد.")


def safe_relative_attachment_path(value: Any) -> str:
    """Validate the exact relative path shape generated by this application."""
    if not isinstance(value, str) or "\\" in value:
        raise ValueError("مسار المرفق غير صالح.")
    path = PurePosixPath(value)
    if path.as_posix() != value or path.is_absolute() or len(path.parts) != 2 or path.parts[0] != ATTACHMENT_FOLDER:
        raise ValueError("مسار المرفق خارج مجلد المرفقات.")
    filename = path.parts[1]
    match = re.fullmatch(r"([0-9a-f]{32})(\.[a-z0-9]+)", filename)
    if not match or match.group(2) not in ALLOWED_EXTENSIONS:
        raise ValueError("اسم ملف المرفق غير آمن.")
    return value


def attachment_path(data_directory: str | Path, relative_path: Any) -> Path:
    relative = safe_relative_attachment_path(relative_path)
    root = Path(data_directory).resolve()
    expected_directory = root / ATTACHMENT_FOLDER
    resolved_directory = expected_directory.resolve()
    if resolved_directory.parent != root:
        raise ValueError("مجلد المرفقات خارج مجلد البيانات.")
    candidate = (root / Path(*PurePosixPath(relative).parts)).resolve()
    if candidate.parent != resolved_directory:
        raise ValueError("مسار المرفق غير آمن.")
    return candidate


def validate_attachment_records(records: Any, *, max_count: int = 2) -> list[dict[str, str]]:
    if records is None:
        return []
    if not isinstance(records, list) or len(records) > max_count:
        raise ValueError("يمكن إرفاق ملفين كحد أقصى لكل أصل.")
    checked: list[dict[str, str]] = []
    for record in records:
        if not isinstance(record, dict):
            raise ValueError("بيانات المرفق غير صالحة.")
        relative = safe_relative_attachment_path(record.get("path"))
        name = safe_original_name(str(record.get("name", "")))
        if Path(name).suffix.lower() != Path(relative).suffix.lower():
            raise ValueError("امتداد اسم المرفق لا يطابق امتداد الملف.")
        checked.append({"path": relative, "name": name})
    return checked


def inspect_source_file(source: str | Path) -> tuple[Path, str, int]:
    path = Path(source).expanduser().resolve(strict=True)
    if not path.is_file():
        raise ValueError("المرفق المحدد ليس ملفًا عاديًا.")
    name = safe_original_name(path.name)
    validate_extension(name)
    size = path.stat().st_size
    if size > MAX_ATTACHMENT_BYTES:
        raise ValueError("الحد الأقصى لحجم كل مرفق هو 20 ميغابايت.")
    with path.open("rb") as stream:
        validate_attachment_content(name, stream.read(1024))
    return path, name, size


def _make_record(name: str) -> dict[str, str]:
    ext = validate_extension(name)
    return {"path": f"{ATTACHMENT_FOLDER}/{uuid.uuid4().hex}{ext}", "name": safe_original_name(name)}


def safe_staging_directory(data_directory: str | Path) -> Path:
    root = Path(data_directory).resolve()
    attachment_dir = root / ATTACHMENT_FOLDER
    stage_dir = attachment_dir / ".staging"
    stage_dir.mkdir(parents=True, exist_ok=True)
    resolved_attachment = attachment_dir.resolve()
    if resolved_attachment.parent != root or stage_dir.resolve().parent != resolved_attachment:
        raise ValueError("مجلد التخزين المؤقت للمرفقات خارج مجلد البيانات.")
    return stage_dir


def stage_attachment_sources(data_directory: str | Path, sources: Iterable[str | Path]) -> tuple[list[dict[str, str]], list[tuple[Path, Path]]]:
    """Copy verified sources to private temporary files; caller finalizes after DB commit."""
    root = Path(data_directory).resolve()
    stage_dir = safe_staging_directory(root)
    records: list[dict[str, str]] = []
    staged: list[tuple[Path, Path]] = []
    try:
        for source in sources:
            path, name, _size = inspect_source_file(source)
            record = _make_record(name)
            final = attachment_path(root, record["path"])
            stage = stage_dir / f"{uuid.uuid4().hex}.tmp"
            staged.append((stage, final))
            shutil.copyfile(path, stage)
            if stage.stat().st_size > MAX_ATTACHMENT_BYTES:
                raise ValueError("الحد الأقصى لحجم كل مرفق هو 20 ميغابايت.")
            with stage.open("rb") as stream:
                validate_attachment_content(name, stream.read(1024))
            records.append(record)
        return records, staged
    except Exception:
        for stage, _final in staged:
            stage.unlink(missing_ok=True)
        raise


def finalize_staged_attachments(staged: Iterable[tuple[Path, Path]]) -> list[Path]:
    created: list[Path] = []
    try:
        for stage, final in staged:
            final.parent.mkdir(parents=True, exist_ok=True)
            if final.exists():
                raise FileExistsError("تعارض غير متوقع في اسم المرفق.")
            os.replace(stage, final)
            created.append(final)
        return created
    except Exception:
        for path in created:
            path.unlink(missing_ok=True)
        raise
    finally:
        for stage, _final in staged:
            stage.unlink(missing_ok=True)


def cleanup_unreferenced_files(data_directory: str | Path, records: Iterable[dict[str, Any]], all_assets: Iterable[dict[str, Any]]) -> None:
    referenced: set[str] = set()
    try:
        for asset in all_assets:
            for record in validate_attachment_records(asset.get("attachments", [])):
                referenced.add(record["path"])
    except (TypeError, ValueError):
        # Corrupt metadata means we cannot prove that any candidate is unreferenced.
        return
    for record in records:
        try:
            relative = safe_relative_attachment_path(record.get("path"))
            if relative not in referenced:
                attachment_path(data_directory, relative).unlink(missing_ok=True)
        except (ValueError, OSError):
            # Never delete an invalid/out-of-root path.
            continue


def attachment_files_for_backup(data_directory: str | Path, assets: Iterable[dict[str, Any]]) -> dict[str, str]:
    files: dict[str, str] = {}
    for asset in assets:
        for record in validate_attachment_records(asset.get("attachments", [])):
            relative = record["path"]
            if relative in files:
                continue
            path = attachment_path(data_directory, relative)
            if not path.is_file():
                raise FileNotFoundError(f"المرفق المشار إليه غير موجود: {record['name']}")
            content = path.read_bytes()
            if len(content) > MAX_ATTACHMENT_BYTES:
                raise ValueError(f"يتجاوز المرفق الحد المسموح: {record['name']}")
            validate_attachment_content(record["name"], content)
            files[relative] = base64.b64encode(content).decode("ascii")
    return files


def decode_backup_attachment_files(data: Any, referenced_paths: set[str] | None = None) -> dict[str, bytes]:
    if data is None:
        if referenced_paths:
            raise ValueError("ملف المرفق غير موجود ضمن محتوى النسخة الاحتياطية.")
        return {}
    if not isinstance(data, dict):
        raise ValueError("خريطة ملفات المرفقات في النسخة غير صالحة.")
    normalized_paths = {safe_relative_attachment_path(path) for path in data}
    if referenced_paths is not None and normalized_paths != referenced_paths:
        raise ValueError("ملف المرفق غير موجود أو أن خريطة الملفات لا تطابق مرفقات الأصول.")
    decoded: dict[str, bytes] = {}
    for raw_path, encoded in data.items():
        relative = safe_relative_attachment_path(raw_path)
        if not isinstance(encoded, str):
            raise ValueError("محتوى مرفق النسخة غير صالح.")
        if len(encoded) > ((MAX_ATTACHMENT_BYTES + 2) // 3) * 4:
            raise ValueError("يتجاوز مرفق النسخة حد 20 ميغابايت.")
        try:
            content = base64.b64decode(encoded, validate=True)
        except (binascii.Error, ValueError) as exc:
            raise ValueError("تعذر فك ترميز مرفق النسخة الاحتياطية.") from exc
        if len(content) > MAX_ATTACHMENT_BYTES:
            raise ValueError("يتجاوز مرفق النسخة حد 20 ميغابايت.")
        validate_attachment_content(Path(relative).name, content)
        decoded[relative] = content
    return decoded


def build_document_archive(
    output_path: str | Path,
    assets: dict[str, Any] | Iterable[dict[str, Any]],
    data_directory: str | Path,
) -> Path:
    """Build a local ZIP with Arabic RTL details and documents for each attached asset."""
    asset_list = [assets] if isinstance(assets, dict) else list(assets)
    output = Path(output_path)
    labels = {
        "code": "رمز الأصل", "accountCode": "رمز الحساب", "name": "اسم الأصل",
        "category": "التصنيف", "department": "الإدارة", "purchaseDate": "تاريخ الشراء",
        "inServiceDate": "تاريخ بدء الاستخدام", "purchaseCost": "تكلفة الشراء",
        "additionalCosts": "التكاليف الإضافية", "salvageValue": "القيمة التخريدية",
        "depreciationMethod": "طريقة الإهلاك", "depreciationInputMode": "أساس إدخال الإهلاك",
        "annualDepreciationRate": "معدل الإهلاك السنوي (%)", "usefulLifeYears": "العمر الإنتاجي (سنوات)",
        "location": "الموقع", "custodian": "المسؤول", "serialNumber": "الرقم التسلسلي",
        "status": "الحالة", "notes": "ملاحظات",
    }
    entries: list[dict[str, Any]] = []
    file_contents: dict[str, bytes] = {}
    for asset in asset_list:
        if not isinstance(asset, dict):
            continue
        records = validate_attachment_records(asset.get("attachments", []))
        if not records:
            continue
        details = {key: asset.get(key, "") for key in labels if asset.get(key) not in (None, "")}
        documents: list[dict[str, Any]] = []
        for record in records:
            source = attachment_path(data_directory, record["path"])
            if not source.is_file():
                raise FileNotFoundError(f"المرفق غير موجود: {record['name']}")
            if source.stat().st_size > MAX_ATTACHMENT_BYTES:
                raise ValueError(f"يتجاوز المرفق حد 20 ميغابايت: {record['name']}")
            content = source.read_bytes()
            if len(content) > MAX_ATTACHMENT_BYTES:
                raise ValueError(f"يتجاوز المرفق حد 20 ميغابايت: {record['name']}")
            validate_attachment_content(record["name"], content)
            if output.resolve() == source.resolve():
                raise ValueError("لا يمكن حفظ التقرير فوق أحد الملفات المرفقة.")
            archive_name = f"files/{Path(record['path']).name}"
            file_contents[archive_name] = content
            documents.append({"path": archive_name, "name": record["name"], "size": len(content)})
        entries.append({"details": details, "documents": documents})
    if not entries:
        raise ValueError("لا توجد أصول ذات مستندات مرفقة.")

    sections: list[str] = []
    for index, entry in enumerate(entries, start=1):
        detail_rows = "".join(
            f'<tr><th>{html.escape(labels[key], quote=True)}</th><td>{html.escape(str(value), quote=True)}</td></tr>'
            for key, value in entry["details"].items()
        )
        documents_html: list[str] = []
        for document in entry["documents"]:
            escaped_name = html.escape(document["name"], quote=True)
            escaped_href = html.escape(document["path"], quote=True)
            if Path(document["path"]).suffix.lower() in IMAGE_EXTENSIONS:
                preview = f'<img src="{escaped_href}" alt="{escaped_name}" style="max-width:100%;max-height:520px">'
            else:
                preview = f'<object data="{escaped_href}" type="application/pdf" width="100%" height="650"><a href="{escaped_href}">فتح ملف PDF</a></object>'
            documents_html.append(f'<section class="document"><h3>{escaped_name}</h3>{preview}<p><a href="{escaped_href}" download="{escaped_name}">تنزيل الملف الأصلي</a></p></section>')
        asset_name = html.escape(str(entry["details"].get("name", "أصل")), quote=True)
        sections.append(f'<article><h2>{index}. {asset_name}</h2><table><tbody>{detail_rows}</tbody></table>{"".join(documents_html)}</article>')

    manifest = {"format": "Aosol asset-document report", "assets": entries}
    index = ('<!doctype html><html lang="ar" dir="rtl"><head><meta charset="utf-8">'
             '<meta name="viewport" content="width=device-width,initial-scale=1"><title>تقرير وثائق الأصول</title>'
             '<style>body{font-family:Tahoma,Arial,sans-serif;max-width:1100px;margin:2rem auto;padding:0 1rem;color:#18263b}article{margin:2rem 0;padding:1.2rem;border:1px solid #d9e0e8;border-radius:10px;overflow-wrap:anywhere;break-inside:avoid}table{border-collapse:collapse;width:100%}th,td{border:1px solid #d9e0e8;padding:.55rem;text-align:right;vertical-align:top}th{background:#eff4f8;width:25%}.document{margin:1.2rem 0;padding:1rem;background:#f8fafc;border:1px solid #e2e8f0;border-radius:8px}img{display:block;object-fit:contain}a{color:#087f79}</style>'
             '</head><body><h1>تقرير وثائق الأصول</h1><p>يتضمن هذا التقرير تفاصيل الأصول التي لها مرفقات والملفات الأصلية المضافة لكل أصل.</p>'
             + "\n".join(sections) + '</body></html>')

    output.parent.mkdir(parents=True, exist_ok=True)
    temp_name: str | None = None
    try:
        with tempfile.NamedTemporaryFile(prefix=".aosol-report-", suffix=".zip", dir=output.parent, delete=False) as temp:
            temp_name = temp.name
        with zipfile.ZipFile(temp_name, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            archive.writestr("index.html", index)
            archive.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
            for archive_name, content in file_contents.items():
                archive.writestr(archive_name, content)
        os.replace(temp_name, output)
        temp_name = None
    finally:
        if temp_name:
            Path(temp_name).unlink(missing_ok=True)
    return output
